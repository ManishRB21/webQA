// ── helpers ────────────────────────────────────────────────────────────────

function hostOf(url: string): string {
  try {
    return new URL(url).host;
  } catch {
    return url;
  }
}

function pathOf(url: string): string {
  try {
    const parsed = new URL(url);
    return (parsed.pathname + parsed.search) || '/';
  } catch {
    return url;
  }
}


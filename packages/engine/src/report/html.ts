// ── client script ──────────────────────────────────────────────────────────

const SCRIPT = `
(function(){
  "use strict";
  var active = { severity:new Set(), category:new Set(), confidence:new Set() };
  var findings = Array.prototype.slice.call(document.querySelectorAll('.finding'));
  var counter = document.getElementById('findingCount');
  var empty = document.getElementById('noMatches');

  function matches(el){
    for (var key in active){
      var set = active[key];
      if (set.size === 0) continue;
      if (!set.has(el.dataset[key])) return false;
    }
    return true;
  }

  function apply(){
    var shown = 0;
    findings.forEach(function(el){
      var ok = matches(el);
      el.classList.toggle('hidden', !ok);
      if (ok) shown++;
    });

    // Hide a severity heading when every finding beneath it is filtered out.
    document.querySelectorAll('.sev-group').forEach(function(group){
      var visible = group.querySelectorAll('.finding:not(.hidden)').length;
      group.classList.toggle('hidden', visible === 0);
    });

    if (counter) counter.textContent = shown + ' of ' + findings.length + ' shown';
    if (empty) empty.classList.toggle('hidden', shown !== 0);
  }

  document.querySelectorAll('.chip[data-filter]').forEach(function(chip){
    chip.addEventListener('click', function(){
      var set = active[chip.dataset.filter];
      if (!set) return;
      var pressed = chip.getAttribute('aria-pressed') === 'true';
      if (pressed) set.delete(chip.dataset.value); else set.add(chip.dataset.value);
      chip.setAttribute('aria-pressed', String(!pressed));
      apply();
    });
  });

  var clear = document.getElementById('clearFilters');
  if (clear) clear.addEventListener('click', function(){
    Object.keys(active).forEach(function(k){ active[k].clear(); });
    document.querySelectorAll('.chip[data-filter]').forEach(function(c){ c.setAttribute('aria-pressed','false'); });
    apply();
  });
})();
`;
